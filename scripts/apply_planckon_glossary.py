GLOBS = [
    ROOT / "model",
    ROOT / "book" / "sources" / "chapters",
    ROOT / "MANIFEST.md",
]


def _sub(text: str, pat: str, repl: str) -> str:
    if "\\" in repl:
        return re.sub(pat, lambda _: repl, text)
    return re.sub(pat, repl, text)


def main() -> None:
    for base in GLOBS:
        paths = [base] if base.is_file() else base.rglob("*")
        for path in paths:
            if path.suffix not in {".md", ".tex"}:
                continue
            if path.name == "00-glossary.md":
                continue
            text = path.read_text(encoding="utf-8")
            orig = text
            for pat, repl in REPLACEMENTS:
                text = _sub(text, pat, repl)
            if text != orig:
                path.write_text(text, encoding="utf-8")
                print("updated", path.relative_to(ROOT))


if __name__ == "__main__":
    main()
